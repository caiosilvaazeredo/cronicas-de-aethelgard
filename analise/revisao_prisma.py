def bibtex_de(r: dict) -> str | None:
    if r.get("doi"):
        try:  # negociação de conteúdo no doi.org: funciona para Crossref e DataCite (arXiv)
            req = urllib.request.Request("https://doi.org/" + r["doi"], headers={"Accept": "application/x-bibtex",
                                                                                  "User-Agent": "prisma-review-script"})
            b = urllib.request.urlopen(req, timeout=60).read().decode("utf8")
            if b.strip().startswith("@"):
                return b
        except Exception:  # noqa: BLE001
            pass
    if r.get("arxiv"):
        autores = " and ".join(a.strip() for a in r["autores"].split(";") if a.strip())
        return (f"@misc{{x,\n  title={{{r['titulo']}}},\n  author={{{autores}}},\n  year={{{r['ano']}}},\n"
                f"  eprint={{{r['arxiv']}}},\n  eprinttype={{arxiv}},\n  howpublished={{arXiv preprint}}\n}}")
    # sem DOI nem arXiv: entrada a partir dos metadados da base, com o endereço do registro
    autores = " and ".join(a.strip() for a in r["autores"].split(";") if a.strip())
    url = r["id"] if str(r["id"]).startswith("http") else ""
    return (f"@misc{{x,\n  title={{{r['titulo']}}},\n  author={{{autores}}},\n  year={{{r['ano']}}},\n"
            f"  howpublished={{{r['veiculo']}}}" + (f",\n  url={{{url}}}" if url else "") + "\n}")


def relatorio(rid: str) -> None:
    cfg = REVISOES[rid]
    pasta = SAIDA / rid
    triaveis, c = preparar(rid)
    ler = lambda nome: {json.loads(l)["uid"]: json.loads(l) for l in (pasta / nome).read_text(encoding="utf8").splitlines() if l.strip()}  # noqa: E731
    tri, ele = ler("triagem.jsonl"), ler("elegibilidade.jsonl")
    # correções da conferência manual (registradas em revisao_manual.json, com justificativa)
    manual = pasta / "revisao_manual.json"
    n_manual = 0
    if manual.exists():
        for uid, d in json.loads(manual.read_text(encoding="utf8")).items():
            if not uid.startswith("_") and uid in ele:
                ele[uid] = dict(ele[uid], **d, modelo="revisão manual")
                n_manual += 1
    exc_t, exc_e = {}, {}
    for r in triaveis:
        d = tri.get(r["uid"])
        if d and d["decisao"] == "exclude":
            exc_t[d["motivo"]] = exc_t.get(d["motivo"], 0) + 1
    passaram = [r for r in triaveis if tri.get(r["uid"], {}).get("decisao") == "include"]
    incluidos = []
    for r in passaram:
        d = ele.get(r["uid"])
        if d and d["decisao"] == "exclude":
            exc_e[d["motivo"]] = exc_e.get(d["motivo"], 0) + 1
        elif d:
            incluidos.append(dict(r, justificativa=d["justificativa"]))
    c.update({"excluidosTriagem": exc_t, "avaliados": len(passaram), "excluidosElegibilidade": exc_e,
              "incluidos": len(incluidos), "naoTriados": len([r for r in triaveis if r["uid"] not in tri]),
              "naoAvaliados": len([r for r in passaram if r["uid"] not in ele]), "decisoesManuais": n_manual})
    (pasta / "contagens.json").write_text(json.dumps(c, ensure_ascii=False, indent=2), encoding="utf8")
    diagrama(rid, c, pasta / "prisma.png")
    with open(pasta / "registros.csv", "w", newline="", encoding="utf8") as fh:
        w = csv.writer(fh)
        w.writerow(["uid", "fontes", "ano", "titulo", "triagem", "motivo_triagem", "elegibilidade", "motivo_elegibilidade", "justificativa"])
        for r in triaveis:
            t, e = tri.get(r["uid"], {}), ele.get(r["uid"], {})
            w.writerow([r["uid"], "|".join(r["fontes"]), r["ano"], r["titulo"], t.get("decisao", ""), t.get("motivo", ""),
                        e.get("decisao", ""), e.get("motivo", ""), e.get("justificativa") or t.get("justificativa", "")])
    incluidos.sort(key=lambda r: (-(r["ano"] or 0), r["titulo"]))
    linhas = [f"| {r['ano']} | {r['titulo']} | {r['autores'].split(';')[0]}{' et al.' if ';' in r['autores'] else ''} | "
              f"{r['veiculo'] or '–'} | {r['doi'] or ('arXiv:' + r['arxiv'] if r['arxiv'] else '–')} |" for r in incluidos]
    (pasta / "incluidos.md").write_text(
        f"# Included studies ({len(incluidos)})\n\n| year | title | first author | venue | DOI / arXiv |\n|---|---|---|---|---|\n"
        + "\n".join(linhas) + "\n", encoding="utf8")
    (pasta / "incluidos.json").write_text(json.dumps(incluidos, ensure_ascii=False, indent=2), encoding="utf8")
    bibs = []
    for i, r in enumerate(incluidos):
        b = bibtex_de(r)
        if b:
            chave = f"rev{rid[:3]}{i + 1:02d}"
            bibs.append(re.sub(r"^\s*@(\w+)\{[^,]*,", rf"@\1{{{chave},", b.strip(), count=1))
            r["chave"] = chave
        time.sleep(1)
    (pasta / "incluidos.bib").write_text("\n\n".join(bibs) + "\n", encoding="utf8")
    (pasta / "incluidos.json").write_text(json.dumps(incluidos, ensure_ascii=False, indent=2), encoding="utf8")
    print(json.dumps(c, ensure_ascii=False, indent=1))


