def coletar_openalex(cfg, pasta: Path) -> list[dict]:
    regs, cursor = [], "*"
    filtro = f"title_and_abstract.search:{cfg['openalex']},from_publication_date:{cfg['desde']},to_publication_date:{cfg['ate']}"
    while cursor:
        url = ("https://api.openalex.org/works?per_page=200&cursor=" + urllib.parse.quote(cursor) +
               "&filter=" + urllib.parse.quote(filtro, safe=":,"))
        d = json.loads(baixar(url))
        (pasta / f"openalex_{len(regs):05d}.json").write_bytes(json.dumps(d).encode())
        for w in d["results"]:
            doi_oa = (w.get("doi") or "").replace("https://doi.org/", "").lower()
            regs.append({"fonte": "OpenAlex", "id": w["id"], "doi": doi_oa,
                         "arxiv": doi_oa.split("arxiv.", 1)[1] if doi_oa.startswith("10.48550/arxiv.") else "", "titulo": w.get("title") or "", "resumo": resumo_openalex(w.get("abstract_inverted_index")),
                         "ano": w.get("publication_year"), "tipo": w.get("type") or "", "lingua": w.get("language") or "",
                         "veiculo": ((w.get("primary_location") or {}).get("source") or {}).get("display_name") or "",
                         "autores": "; ".join(a["author"]["display_name"] for a in (w.get("authorships") or [])[:8])})
        cursor = d["meta"].get("next_cursor") if d["results"] else None
        time.sleep(1)
    return regs


def coletar_arxiv(cfg, pasta: Path) -> list[dict]:
    regs, inicio = [], 0
    desde, ate = cfg["desde"].replace("-", "") + "0000", cfg["ate"].replace("-", "") + "2359"
    consulta = f"({cfg['arxiv']}) AND submittedDate:[{desde} TO {ate}]"
    while True:
        url = ("https://export.arxiv.org/api/query?max_results=200&start=" + str(inicio) +
               "&search_query=" + urllib.parse.quote(consulta))
        xml = baixar(url).decode("utf8")
        (pasta / f"arxiv_{inicio:05d}.xml").write_text(xml, encoding="utf8")
        entradas = re.findall(r"<entry>(.*?)</entry>", xml, re.S)
        for e in entradas:
            g = lambda tag: (re.search(rf"<{tag}[^>]*>(.*?)</{tag}>", e, re.S) or [None, ""])[1]  # noqa: E731
            aid = g("id").rsplit("/abs/", 1)[-1]
            doi = (re.search(r"<arxiv:doi[^>]*>(.*?)</arxiv:doi>", e) or [None, ""])[1].lower()
            regs.append({"fonte": "arXiv", "id": aid, "doi": doi, "arxiv": re.sub(r"v\d+$", "", aid),
                         "titulo": " ".join(g("title").split()), "resumo": " ".join(g("summary").split()),
                         "ano": int(g("published")[:4]) if g("published") else None, "tipo": "preprint", "lingua": "en",
                         "veiculo": "arXiv", "autores": "; ".join(re.findall(r"<name>(.*?)</name>", e)[:8])})
        if len(entradas) < 200:
            break
        inicio += 200
        time.sleep(3)
    return regs


def coletar_s2(cfg, pasta: Path) -> list[dict]:
    regs, token, n = [], None, 0
    campos = "title,abstract,year,externalIds,venue,authors,publicationTypes"
    while True:
        url = ("https://api.semanticscholar.org/graph/v1/paper/search/bulk?fields=" + campos + "&year=" + cfg["anos_s2"] +
               "&query=" + urllib.parse.quote(cfg["s2"]) + (f"&token={token}" if token else ""))
        d = json.loads(baixar(url))
        (pasta / f"s2_{n:03d}.json").write_bytes(json.dumps(d).encode())
        n += 1
        for p in d.get("data", []):
            ext = p.get("externalIds") or {}
            regs.append({"fonte": "Semantic Scholar", "id": p["paperId"], "doi": (ext.get("DOI") or "").lower(),
                         "arxiv": ext.get("ArXiv") or "", "titulo": p.get("title") or "", "resumo": p.get("abstract") or "",
                         "ano": p.get("year"), "tipo": ",".join(p.get("publicationTypes") or []), "lingua": "",
                         "veiculo": p.get("venue") or "", "autores": "; ".join(a.get("name", "") for a in (p.get("authors") or [])[:8])})
        token = d.get("token")
        if not token:
            break
        time.sleep(2)
    return regs


def coletar(rid: str) -> None:
    cfg = REVISOES[rid]
    pasta = SAIDA / rid
    bruto = pasta / "bruto"
    bruto.mkdir(parents=True, exist_ok=True)
    todos = []
    for nome, f in (("OpenAlex", coletar_openalex), ("arXiv", coletar_arxiv), ("Semantic Scholar", coletar_s2)):
        regs = f(cfg, bruto)
        print(f"{rid}: {nome}: {len(regs)} registros")
        todos += regs
        time.sleep(3)
    with open(pasta / "identificados.jsonl", "w", encoding="utf8") as fh:
        for r in todos:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")
    (pasta / "busca.json").write_text(json.dumps({
        "data_da_busca": time.strftime("%Y-%m-%d"), "periodo": [cfg["desde"], cfg["ate"]],
        "strings": {"OpenAlex (title_and_abstract.search)": cfg["openalex"], "arXiv (abstract)": cfg["arxiv"],
                    "Semantic Scholar (bulk search)": cfg["s2"]}}, ensure_ascii=False, indent=2), encoding="utf8")


