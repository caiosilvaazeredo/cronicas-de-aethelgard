ESQUEMA = {"type": "object", "properties": {"decisoes": {"type": "array", "items": {"type": "object", "properties": {
    "n": {"type": "integer"}, "decisao": {"type": "string", "enum": ["include", "exclude"]},
    "motivo": {"type": "string"}, "justificativa": {"type": "string"}},
    "required": ["n", "decisao", "motivo", "justificativa"]}}}, "required": ["decisoes"]}


def chamar_claude(modelo: str, sistema: str, usuario: str) -> dict:
    args = ["claude", "-p", "--output-format", "json", "--model", modelo, "--system-prompt", sistema, "--tools", "",
            "--strict-mcp-config", "--setting-sources", "", "--no-session-persistence",
            "--json-schema", json.dumps(ESQUEMA)]
    for tentativa in range(6):
        p = subprocess.run(args, input=usuario, capture_output=True, text=True, timeout=900, cwd="/tmp")
        try:
            d = json.loads(p.stdout)
        except json.JSONDecodeError:
            time.sleep(20 * (tentativa + 1))
            continue
        if d.get("is_error"):
            texto = str(d.get("result", ""))
            m = re.search(r"resets? (\d{1,2})(?::(\d{2}))?\s*(am|pm)", texto, re.I)
            time.sleep(600 if m else 30 * (tentativa + 1))
            continue
        if d.get("structured_output"):
            return d["structured_output"]
        try:
            return json.loads(d.get("result", ""))
        except json.JSONDecodeError:
            time.sleep(10)
    raise RuntimeError("claude -p falhou repetidamente")


def sistema_prompt(cfg, etapa: str) -> str:
    excl = "\n".join(f"- {k}: {v}" for k, v in cfg["exclusao"].items())
    incl = "\n".join(f"- {x}" for x in cfg["inclusao"])
    rigor = ("Screening stage: include when the record plausibly meets ALL inclusion criteria; when in doubt, include."
             if etapa == "triagem" else
             "Eligibility stage (stricter): include only when the abstract makes clear that ALL inclusion criteria are "
             "met and the work is directly relevant to the review question; otherwise exclude with the most specific reason.")
    return (f"You are a systematic-review screener following PRISMA 2020.\nReview question: {cfg['pergunta']}\n\n"
            f"Inclusion criteria:\n{incl}\n\nExclusion reasons (use the code as 'motivo' when excluding; use 'I' when including):\n{excl}\n\n"
            f"{rigor}\nJudge only from the title and abstract given. Answer with one decision per record number, "
            f"with a one-sentence justification.")


def triar_etapa(rid: str, regs: list[dict], etapa: str, modelo: str, lote: int) -> dict:
    cfg = REVISOES[rid]
    arq = SAIDA / rid / f"{etapa}.jsonl"
    feitos = {}
    if arq.exists():
        for l in arq.read_text(encoding="utf8").splitlines():
            if l.strip():
                d = json.loads(l)
                feitos[d["uid"]] = d
    pendentes = [r for r in regs if r["uid"] not in feitos]
    sistema = sistema_prompt(cfg, etapa)
    for i in range(0, len(pendentes), lote):
        grupo = pendentes[i:i + lote]
        texto = "\n\n".join(f"[{n}] Title: {r['titulo']}\nYear: {r['ano']}\nVenue: {r['veiculo']}\nAbstract: {r['resumo'][:2500]}"
                            for n, r in enumerate(grupo, 1))
        out = chamar_claude(modelo, sistema, f"Records to {('screen' if etapa == 'triagem' else 'assess')}:\n\n{texto}")
        por_n = {d["n"]: d for d in out.get("decisoes", [])}
        with open(arq, "a", encoding="utf8") as fh:
            for n, r in enumerate(grupo, 1):
                d = por_n.get(n)
                if d is None:
                    continue  # fica para a próxima rodada
                reg = {"uid": r["uid"], "decisao": d["decisao"], "motivo": d["motivo"], "justificativa": d["justificativa"],
                       "modelo": modelo}
                fh.write(json.dumps(reg, ensure_ascii=False) + "\n")
                feitos[r["uid"]] = reg
        print(f"{rid} {etapa}: {min(i + lote, len(pendentes))}/{len(pendentes)}")
    return feitos


def preparar(rid: str) -> tuple[list[dict], dict]:
    cfg = REVISOES[rid]
    pasta = SAIDA / rid
    regs = [json.loads(l) for l in (pasta / "identificados.jsonl").read_text(encoding="utf8").splitlines() if l.strip()]
    por_fonte = {}
    for r in regs:
        por_fonte[r["fonte"]] = por_fonte.get(r["fonte"], 0) + 1
    unicos, dup = deduplicar(regs)
    a0, a1 = int(cfg["desde"][:4]), int(cfg["ate"][:4])
    sem_resumo = [r for r in unicos if len((r.get("resumo") or "").split()) < 30]
    fora = [r for r in unicos if r not in sem_resumo and not (r.get("ano") and a0 <= int(r["ano"]) <= a1)]
    triaveis = [r for r in unicos if r not in sem_resumo and r not in fora]
    for r in triaveis:
        r["uid"] = r["doi"] or ("arxiv:" + r["arxiv"] if r["arxiv"] else "t:" + norm_titulo(r["titulo"]))
    contagens = {"porFonte": por_fonte, "identificados": len(regs), "duplicatas": dup,
                 "semResumo": len(sem_resumo), "foraDoPeriodo": len(fora), "triados": len(triaveis)}
    return triaveis, contagens


def triar(rid: str) -> None:
    triaveis, _ = preparar(rid)
    tri = triar_etapa(rid, triaveis, "triagem", "claude-sonnet-5", 20)
    passaram = [r for r in triaveis if tri.get(r["uid"], {}).get("decisao") == "include"]
    triar_etapa(rid, passaram, "elegibilidade", "claude-opus-5-5", 10)


